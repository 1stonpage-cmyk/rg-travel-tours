/**
 * The guest credential check — booking ref + email (§7), in ONE place.
 *
 * **This is an extraction, not a new idea.** `checkout.bookingLookup` has
 * matched a ref against a case-insensitive lead email since Week 3, and
 * Week 4's portal login needs exactly the same check. Two copies of "do
 * these credentials match this booking?" would be two things that have to
 * agree forever, and the day they stop agreeing is the day one surface
 * admits a guest the other refuses. So the lookup and the login both call
 * this.
 *
 * ## It returns an id or null, and never a reason
 *
 * §7: "Same generic error for wrong ref or wrong email (don't reveal
 * which)." The cleanest way to keep that promise is for the function that
 * knows the difference to be incapable of reporting it — so the two failure
 * modes are the same `null` here, and the caller has nothing to leak even
 * if it wanted to. A caller that wanted to distinguish them would have to
 * write a second query, which is a visible act rather than an accident.
 *
 * ## Why the ref is matched exactly and the email case-insensitively
 *
 * Refs are generated by `generateBookingRef()` from a fixed uppercase
 * alphabet, so uppercasing the input is normalisation rather than a
 * comparison rule. Emails are stored as the guest typed them at checkout,
 * which may be `Guest@Example.test`, and §7 requires the match to ignore
 * case — hence `LOWER()` on the column rather than on the input alone.
 *
 * Both sides are trimmed, because a guest pasting a ref out of an email
 * brings whitespace with it and "your booking could not be found" for a
 * trailing space is a support call.
 */
import { and, eq, sql } from 'drizzle-orm';
import { getDb } from '../db/client';
import { bookings } from '../db/schema';

/** The normalised form of a booking ref: trimmed and uppercased. */
export function normalizeBookingRef(ref: string): string {
  return ref.trim().toUpperCase();
}

/** The normalised form of a lead email for comparison: trimmed and lowercased. */
export function normalizeLeadEmail(email: string): string {
  return email.trim().toLowerCase();
}

/**
 * The booking these credentials identify, or `null`.
 *
 * One query, both conditions. Doing the email comparison in SQL rather than
 * reading the row and comparing in JS matters for more than tidiness: a row
 * that does not match is never loaded, so there is no object in memory
 * holding another guest's email for a caller to accidentally return. (The
 * lookup resolver this replaces did load it, and carried a comment warning
 * the field must never be returned — a warning that is now unnecessary.)
 *
 * `LOWER(lead_email)` cannot use an index on that column, which is fine at
 * this scale and for this shape: the `ref` equality is the selective half
 * and `bookings.ref` is unique, so at most one row is ever examined.
 */
export async function findBookingByCredentials(
  ref: string,
  email: string,
): Promise<{ id: number } | null> {
  const [booking] = await getDb()
    .select({ id: bookings.id })
    .from(bookings)
    .where(
      and(
        eq(bookings.ref, normalizeBookingRef(ref)),
        sql`LOWER(${bookings.leadEmail}) = ${normalizeLeadEmail(email)}`,
      ),
    )
    .limit(1);

  return booking ?? null;
}
